#!/usr/bin/env node
/**
 * Classify every English body line that sits on a non-English Business/Studio page by WHERE the English comes from
 * (read-only; never edits a page or a translation).
 *
 *   node scripts/classify-english-remainder.mjs [--json out.json]
 *
 * "English line" = the same definition as scripts/qa-lang-mix.mjs (≥25 chars, reads as English, not marked lang="en").
 * Source classes, checked in this order:
 *   reframe-notice       text that the confirmed-model layer (business-model-pages / business-model-reframe) writes in English
 *                        for the 7 locales on purpose (notice, CTA labels) - waiting for a native reviewer
 *   english-in-pack      the language pack for this language (scripts/i18n/packs/<lang>) holds the same English text:
 *                        the translation step returned English / was never translated
 *   english-source-only  the English text exists in a copy script but the language pack has no entry for it: pure fallback
 *   unknown-source       not found in any tracked source: generated by a template or another layer - trace needed
 * No class is a quality verdict and none of them approves a translation.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { PAGES } from "./business-model-pages.mjs";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const LANGS = ["ja", "es", "pt-br", "fr", "de", "hi", "id"];
const EN_WORDS = new Set("the and with your for from that this are you our can will not have has into about more than their which when what how all one use used using work works build built design designed we it is of to in on as by or an be at a".split(" "));
const argv = process.argv.slice(2);
const jsonOut = argv.includes("--json") ? argv[argv.indexOf("--json") + 1] : null;
const norm = (s) => s.replace(/<[^>]+>/g, " ").replace(/\\n/g, " ").replace(/&amp;/g, "&").replace(/&#39;|&rsquo;|’/g, "'").replace(/&quot;|\\"/g, '"').replace(/\s+/g, " ").trim().toLowerCase();
const score = (l) => l.toLowerCase().split(/[^a-z']+/).filter((w) => EN_WORDS.has(w)).length;
/* identical to scripts/qa-lang-mix.mjs looksEnglish() so the totals are comparable with its report */
function looksEnglish(line, lang) {
  if (lang === "ja") return !/[぀-ヿ一-鿿]/.test(line) && score(line) >= 2;
  if (lang === "hi") return !/[ऀ-ॿ]/.test(line) && score(line) >= 2;
  return score(line) >= 3;
}

function bodyLines(html) {
  const main = (html.match(/<main[\s\S]*?<\/main>/i) || [html])[0].replace(/<(script|style|svg)[\s\S]*?<\/\1>/gi, " ");
  const marked = new Set();
  main.replace(/<(\w+)[^>]*\blang="en"[^>]*>([\s\S]*?)<\/\1>/gi, (_, __, inner) => { marked.add(inner.replace(/<[^>]+>/g, " ").replace(/\s+/g, " ").trim()); return ""; });
  const text = main.replace(/<\/(p|h[1-6]|li|div|section|span|a|dt|dd|td|th|button|summary|label|option)>/gi, "\n").replace(/<[^>]+>/g, " ")
    .replace(/&amp;/g, "&").replace(/&#39;/g, "'").replace(/&quot;/g, '"');
  return { lines: text.split("\n").map((l) => l.replace(/\s+/g, " ").trim()).filter((l) => l.length >= 25), markedText: [...marked].join(" ") };
}

const scriptsDir = path.join(ROOT, "scripts");
const copySources = fs.readdirSync(scriptsDir).filter((f) => f.endsWith(".mjs") && /copy|data|catalog|pages|pillar|flows|visuals|resources|store|studio|company|reframe/.test(f))
  .map((f) => ({ file: `scripts/${f}`, text: norm(fs.readFileSync(path.join(scriptsDir, f), "utf8")) }));
const reframe = copySources.filter((s) => /business-model-(pages|reframe)\.mjs$/.test(s.file));
const packText = {};
for (const lang of LANGS) {
  const dir = path.join(scriptsDir, "i18n", "packs", lang);
  packText[lang] = fs.existsSync(dir) ? fs.readdirSync(dir).filter((f) => f.endsWith(".json")).map((f) => ({ file: `scripts/i18n/packs/${lang}/${f}`, text: norm(fs.readFileSync(path.join(dir, f), "utf8")) })) : [];
}
const key = (line) => norm(line).slice(0, 48);

const result = { definition: "see header", languages: {} };
for (const lang of LANGS) {
  const cls = {}, byFile = {}, perPage = {};
  for (const [pageKey, meta] of Object.entries(PAGES)) {
    const f = path.join(ROOT, lang, pageKey, "index.html");
    if (!fs.existsSync(f)) continue;
    const html = fs.readFileSync(f, "utf8");
    if (/http-equiv="refresh"/i.test(html) && !/<main\b/.test(html)) continue;
    const { lines, markedText } = bodyLines(html);
    for (const l of lines) {
      if (!looksEnglish(l, lang) || markedText.includes(l.slice(0, 40))) continue;
      const k = key(l);
      let c, src = null;
      if (reframe.some((s) => s.text.includes(k))) { c = "reframe-notice"; src = reframe.find((s) => s.text.includes(k)).file; }
      else if (packText[lang].some((s) => s.text.includes(k))) { c = "english-in-pack"; src = packText[lang].find((s) => s.text.includes(k)).file; }
      else if (copySources.some((s) => s.text.includes(k))) { c = "english-source-only"; src = copySources.find((s) => s.text.includes(k)).file; }
      else c = "unknown-source";
      cls[c] = (cls[c] || 0) + 1;
      if (src) byFile[src] = (byFile[src] || 0) + 1;
      const pk = `${meta[0]}:${pageKey}`;
      perPage[pk] = perPage[pk] || { total: 0 };
      perPage[pk].total += 1; perPage[pk][c] = (perPage[pk][c] || 0) + 1;
    }
  }
  const total = Object.values(cls).reduce((a, b) => a + b, 0);
  result.languages[lang] = { total, classes: cls, topSources: Object.entries(byFile).sort((a, b) => b[1] - a[1]).slice(0, 8), pages: Object.keys(perPage).length, perPage };
}
if (jsonOut) fs.writeFileSync(jsonOut, `${JSON.stringify(result, null, 1)}\n`);
console.log("classify-english-remainder: lines by source class (A/B/C/D pages together)");
for (const lang of LANGS) {
  const r = result.languages[lang];
  console.log(`  ${lang.padEnd(5)} total ${String(r.total).padStart(4)} · ${["reframe-notice", "english-in-pack", "english-source-only", "unknown-source"].map((c) => `${c} ${r.classes[c] || 0}`).join(" · ")}`);
}

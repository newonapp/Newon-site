#!/usr/bin/env node
/**
 * ONGIL module cache versions (import map).
 *
 * ongil-start/index.html loads one ES module entry with a version query (app.js?v=…). Every other module is reached
 * through relative imports ("./router.js"), which carry no version, so a browser can keep an old copy of a changed
 * module in its HTTP cache (GitHub Pages: max-age 600) and run it next to the new ones — a new import of a missing export
 * stops the whole app. An import map in index.html gives every module a URL that changes exactly when its content
 * changes (?v=<first 12 hex of SHA-256>), so old and new modules are never mixed and unchanged modules stay cached.
 * Browsers without import maps ignore the block and behave as before.
 *
 *   node scripts/ongil-module-versions.mjs           check: exit 1 when the map in index.html is out of date
 *   node scripts/ongil-module-versions.mjs --write   rewrite the map in index.html
 *
 * The entry (app.js) keeps its own ?v= in the <script type="module"> tag, as before.
 */
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const JS_DIR = path.join(ROOT, 'ongil-start', 'js');
const INDEX = path.join(ROOT, 'ongil-start', 'index.html');
const URL_BASE = '/ongil-start/js/';
const ENTRY = 'app.js';
export const START = '<!-- ongil-module-versions:start (generated by scripts/ongil-module-versions.mjs --write; do not edit) -->';
export const END = '<!-- ongil-module-versions:end -->';

export function moduleVersion(file) {
  return crypto.createHash('sha256').update(fs.readFileSync(path.join(JS_DIR, file))).digest('hex').slice(0, 12);
}
export function modules() {
  return fs.readdirSync(JS_DIR).filter((f) => f.endsWith('.js') && f !== ENTRY).sort();
}
export function expectedMap() {
  const imports = {};
  for (const f of modules()) imports[URL_BASE + f] = URL_BASE + f + '?v=' + moduleVersion(f);
  return { imports };
}
export function block(map = expectedMap()) {
  return START + '\n    <script type="importmap">\n' + JSON.stringify(map, null, 2).split('\n').map((l) => '    ' + l).join('\n') + '\n    </script>\n    ' + END;
}
export function currentBlock(html) {
  const a = html.indexOf(START), b = html.indexOf(END);
  return a >= 0 && b > a ? html.slice(a, b + END.length) : null;
}

function main() {
  const html = fs.readFileSync(INDEX, 'utf8');
  const want = block();
  const have = currentBlock(html);
  if (process.argv.includes('--write')) {
    let next;
    if (have) next = html.replace(have, want);
    else {
      const entry = html.indexOf('<script type="module" src="/ongil-start/js/' + ENTRY);
      if (entry < 0) throw new Error('module entry not found in ongil-start/index.html');
      next = html.slice(0, entry) + want + '\n    ' + html.slice(entry);
    }
    if (next !== html) fs.writeFileSync(INDEX, next);
    console.log('ongil-module-versions: ' + modules().length + ' modules ' + (next !== html ? 'written' : 'already current'));
    return;
  }
  if (have !== want) { console.error('ongil-module-versions: import map in ongil-start/index.html is out of date — run node scripts/ongil-module-versions.mjs --write'); process.exit(1); }
  console.log('ongil-module-versions: OK (' + modules().length + ' modules)');
}
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();

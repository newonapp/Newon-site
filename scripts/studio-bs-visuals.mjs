/** @param {string} slug */
export function studioHeroVisual(slug) {
  const map = {
    "brand-strategy": visualBrandStack,
    naming: visualBrandStack,
    identity: visualBrandStack,
    "logo-design": visualBrandStack,
    "web-design": visualWebDetail,
    "app-ui-ux": visualAppDetail,
    "landing-page-design": visualLandingDetail,
    "product-design": visualSystem,
    "social-content": visualContentFeed,
    campaign: visualContentFeed,
    "visual-content": visualContentFeed,
    "character-lab": visualCharacterLab,
    "digital-stickers": () => visualStatusPanel("COMING SOON", "Digital Stickers"),
    "newon-character": () => visualStatusPanel("INTERNAL", "Newon Character"),
    "experimental-ip": visualCharacterLab,
  };
  const fn = map[slug];
  return fn ? fn() : visualBrandStack();
}

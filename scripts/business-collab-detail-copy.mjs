function koString(value) {
  if (typeof value !== "string") return value;
  return KO_STRINGS[value] ?? value;
}

function localizeKoCopy(copy) {
  const out = { ...copy };
  for (const [key, value] of Object.entries(out)) {
    if (typeof value === "string") {
      out[key] = koString(value);
    } else if (Array.isArray(value)) {
      out[key] = value.map((item) => {
        if (typeof item === "string") return koString(item);
        if (item && typeof item === "object") {
          const row = { ...item };
          if (row.title) row.title = koString(row.title);
          if (row.label) row.label = koString(row.label);
          return row;
        }
        return item;
      });
    }
  }
  return out;
}

export function getCollabCopy(slug, lang) {
  const pack = lang === "ko" ? KO : EN;
  const page = pack[slug];
  if (!page) return null;
  const merged = { ...pack.common, ...page };
  return lang === "ko" ? localizeKoCopy(merged) : merged;
}

